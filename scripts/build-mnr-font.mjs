/**
 * MNR2007: the build-time half of SPEC.md §2.
 *
 * Two outputs from one source file, and neither is a runtime check:
 *   1. public/fonts/MNR2007.woff2 — the WHOLE font, never subsetted. It drops to ~42 %
 *      as WOFF2, a bigger win than subsetting at no cost in coverage, so a pictogram
 *      cannot go missing on a day nobody sampled.
 *   2. lib/mnr-coverage.ts — the codepoints the font's own cmap covers, as a Set the app
 *      imports. `document.fonts.check()` cannot see a missing glyph: the font loads and
 *      the codepoint still renders .notdef. This is a versioning problem, not a fixed
 *      list — MÁV added 108 glyphs between two copies of this file — so the list is
 *      generated, not hard-coded.
 *
 * Re-run whenever MNR2007.ttf is replaced. That is the whole maintenance story.
 *
 *   node scripts/build-mnr-font.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ttf = join(root, 'public/fonts/MNR2007.ttf');
const woff2 = join(root, 'public/fonts/MNR2007.woff2');
const out = join(root, 'lib/mnr-coverage.ts');

/* ---- 1. the cmap ---------------------------------------------------------
   Parsed here rather than with a font library: this reads four table formats and
   is the only thing the build needs from the file. */
const buf = readFileSync(ttf);
const u8 = (o) => buf.readUInt8(o);
const u16 = (o) => buf.readUInt16BE(o);
const i16 = (o) => buf.readInt16BE(o);
const u32 = (o) => buf.readUInt32BE(o);

const numTables = u16(4);
let cmapOffset = -1;
for (let i = 0; i < numTables; i++) {
  const rec = 12 + i * 16;
  if (buf.toString('ascii', rec, rec + 4) === 'cmap') cmapOffset = u32(rec + 8);
}
if (cmapOffset < 0) throw new Error('no cmap table in MNR2007.ttf');

const codes = new Set();

const readSubtable = (off) => {
  const format = u16(off);
  if (format === 0) {
    for (let c = 0; c < 256; c++) if (u8(off + 6 + c)) codes.add(c);
  } else if (format === 4) {
    const segX2 = u16(off + 6);
    const seg = segX2 / 2;
    const ends = off + 14;
    const starts = ends + segX2 + 2;
    const deltas = starts + segX2;
    const ranges = deltas + segX2;
    for (let s = 0; s < seg; s++) {
      const end = u16(ends + s * 2);
      const start = u16(starts + s * 2);
      const delta = i16(deltas + s * 2);
      const rangeOff = u16(ranges + s * 2);
      if (start === 0xffff) continue;
      for (let c = start; c <= end && c !== 0x10000; c++) {
        let gid;
        if (rangeOff === 0) gid = (c + delta) & 0xffff;
        else {
          const gi = ranges + s * 2 + rangeOff + (c - start) * 2;
          gid = u16(gi);
          if (gid !== 0) gid = (gid + delta) & 0xffff;
        }
        if (gid !== 0) codes.add(c);
      }
    }
  } else if (format === 6) {
    const first = u16(off + 6);
    const count = u16(off + 8);
    for (let i = 0; i < count; i++) if (u16(off + 10 + i * 2)) codes.add(first + i);
  } else if (format === 12) {
    const groups = u32(off + 12);
    for (let g = 0; g < groups; g++) {
      const rec = off + 16 + g * 12;
      const start = u32(rec), end = u32(rec + 4);
      for (let c = start; c <= end; c++) codes.add(c);
    }
  }
};

const tableCount = u16(cmapOffset + 2);
for (let i = 0; i < tableCount; i++) {
  readSubtable(cmapOffset + u32(cmapOffset + 4 + i * 8 + 4));
}

const sorted = [...codes].sort((a, b) => a - b);
writeFileSync(out, `/* GENERATED by scripts/build-mnr-font.mjs from public/fonts/MNR2007.ttf.
   Do not edit: re-run the script when the font file is replaced (SPEC.md §2).
   ${sorted.length} codepoints, ${sorted[0]} to ${sorted[sorted.length - 1]}. */

export const MNR_COVERAGE: ReadonlySet<number> = new Set([
${chunk(sorted)}]);

/** A pictogram falls back per codepoint, not per font: the font can load and the glyph
 *  still render .notdef. SPEC.md §2, §10 #14. */
export const hasGlyph = (fontCode: number | null | undefined) =>
  fontCode != null && MNR_COVERAGE.has(fontCode);
`);

function chunk(list) {
  const lines = [];
  for (let i = 0; i < list.length; i += 16) lines.push('  ' + list.slice(i, i + 16).join(', ') + ',');
  return lines.join('\n') + '\n';
}

/* ---- 2. the woff2 -------------------------------------------------------- */
let converted = false;
try {
  execFileSync('woff2_compress', [ttf], { stdio: 'pipe' });
  converted = existsSync(woff2);
} catch {
  converted = false;
}

console.log(`MNR2007: ${sorted.length} codepoints -> lib/mnr-coverage.ts`);
console.log(converted
  ? `MNR2007: whole font converted -> public/fonts/MNR2007.woff2`
  : `MNR2007: woff2_compress not available, left public/fonts/MNR2007.woff2 as it stands`);
